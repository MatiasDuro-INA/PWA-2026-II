

// 1. Declarada
function duplicar (numero) {
    return numero * 2
}
// console.log(duplicar(5));

// 2. Expresada (una funcion, guardada en una variable)
const duplicarExpresada = function(numero){
    return numero * 2
}

// console.log(duplicarExpresada(6))

// 3. Funcion Flecha o Arrow function
const duplicarArrow = (numero) => {
    return numero * 2
}

